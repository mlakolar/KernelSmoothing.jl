# Reference values for the local likelihood fits of KernelSmoothing.jl: at each point,
# R's glm with the kernel weights as prior weights, and the sandwich variance of the
# intercept of the local polynomial in the linear predictor.
i <- 1:500
phi <- round(0.6180339887498949 * 2^30) / 2^30   # 30 bits, so that the data agree with Julia's
x <- (i * phi) %% 1
pr <- 1 / (1 + exp(-(2 * sin(2 * pi * x))))
c2 <- round(0.7548776662466927 * 2^30) / 2^30
c3 <- round(0.5698402909980532 * 2^30) / 2^30
yb <- as.numeric(((i * c2) %% 1) < pr)
yp <- floor(-log(1 - ((i * c3) %% 1)) * exp(1 + sin(2 * pi * x)))   # counts with mean about exp(1 + sin 2πx)
w <- 1 + (i %% 3)
epa <- function(u) pmax(0.75 * (1 - u^2), 0)
f <- function(v) paste(sprintf("%.17g", v), collapse = ", ")
cat("# generated by locallik_golden.R with", R.version.string, "\n")
cat("const LOCALLIK = [\n")
for (cfg in list(list(fam = "logit", y = "yb", p = 1, h = 0.2), list(fam = "logit", y = "yb", p = 2, h = 0.3),
                 list(fam = "logit", y = "yb", p = 0, h = 0.15), list(fam = "poisson", y = "yp", p = 1, h = 0.2),
                 list(fam = "poisson", y = "yp", p = 2, h = 0.3), list(fam = "logit", y = "yb", p = 1, h = 0.2, wt = TRUE))) {
  y <- get(cfg$y)
  pts <- c(0.05, 0.3, 0.5, 0.8)
  est <- se <- numeric(length(pts))
  for (j in seq_along(pts)) {
    u <- (x - pts[j]) / cfg$h
    kw <- epa(u) * if (isTRUE(cfg$wt)) w else 1
    keep <- kw > 0
    Z <- outer(u[keep], 0:cfg$p, "^")
    fam <- if (cfg$fam == "logit") binomial() else poisson()
    g <- suppressWarnings(glm.fit(Z, y[keep], weights = kw[keep], family = fam, control = glm.control(epsilon = 1e-14, maxit = 100)))
    mu <- g$fitted.values; V <- fam$variance(mu)
    A <- crossprod(Z * (kw[keep] * V), Z)
    B <- crossprod(Z * (kw[keep] * (y[keep] - mu)), Z * (kw[keep] * (y[keep] - mu)))
    Vs <- solve(A, t(solve(A, B)))
    est[j] <- g$coefficients[1]; se[j] <- sqrt(Vs[1, 1])
  }
  cat(sprintf("  (family = :%s, y = \"%s\", degree = %d, h = %s, weighted = %s, points = [%s],\n   eta = [%s],\n   se = [%s]),\n",
              cfg$fam, cfg$y, cfg$p, cfg$h, tolower(isTRUE(cfg$wt)), f(pts), f(est), f(se)))
}
cat("]\n")
