# Reference values from rdpower for the power calculations of KernelSmoothing.jl. The
# library with rdpower is the first argument, or on the library path.
RLIB <- commandArgs(trailingOnly = TRUE)[1]
if (!is.na(RLIB)) .libPaths(c(RLIB, .libPaths()))
suppressPackageStartupMessages(library(rdpower))
f <- function(v) paste(sprintf("%.17g", v), collapse = ", ")
vec <- function(name, v) cat("const ", name, " = [", f(v), "]\n", sep = "")
cat("# generated by rdpower_golden.R with rdpower", as.character(packageVersion("rdpower")), "and rdrobust",
    as.character(packageVersion("rdrobust")), "\n")
i <- 1:1000
a <- round(c(0.6180339887498949, 0.4142135623730951) * 2^30) / 2^30   # exact products
x <- 2 * ((i * a[1]) %% 1) - 1
y <- 0.5 + 0.8 * x - 0.3 * x^2 + 0.4 * (x >= 0) + 0.5 * qnorm(((i * a[2]) %% 1) * 0.998 + 0.001)
vec("X", x); vec("Y", y)
sink(tempfile())
p1 <- rdpower(data = cbind(y, x), tau = 0.3)
p2 <- rdpower(data = cbind(y, x), tau = 0.5, alpha = 0.1)
p3 <- rdpower(data = cbind(y, x), tau = 0.3, sampsi = 2 * c(p1$Nh.l, p1$Nh.r))
s1 <- rdsampsi(data = cbind(y, x), tau = 0.3)
s2 <- rdsampsi(data = cbind(y, x), tau = 0.2, beta = 0.9, alpha = 0.1)
s3 <- rdsampsi(data = cbind(y, x), tau = 0.25, beta = 0.7)
s4 <- rdsampsi(data = cbind(y, x), tau = 0.4, beta = 0.95, alpha = 0.01)
s5 <- rdsampsi(data = cbind(y, x), tau = -0.15)
sink()
vec("POWER", c(p1$power.rbc, p2$power.rbc, p3$power.rbc)); vec("SE", c(p1$se.rbc, p2$se.rbc, p3$se.rbc))
vec("SAMPSI", c(s1$sampsi.tot, s2$sampsi.tot))
vec("SAMPSI2", c(s3$sampsi.tot, s4$sampsi.tot, s5$sampsi.tot))
