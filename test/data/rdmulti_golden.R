# Reference values from rdmulti for the designs with several cutoffs of
# KernelSmoothing.jl. The library with rdmulti is the first argument, or on the
# library path.
RLIB <- commandArgs(trailingOnly = TRUE)[1]
if (!is.na(RLIB)) .libPaths(c(RLIB, .libPaths()))
suppressPackageStartupMessages(library(rdmulti))
f <- function(v) { s <- sprintf("%.17g", v); s[is.na(v)] <- "NaN"; paste(s, collapse = ", ") }
vec <- function(name, v) cat("const ", name, " = [", f(v), "]\n", sep = "")
cat("# generated by rdmulti_golden.R with rdmulti", as.character(packageVersion("rdmulti")), "and rdrobust",
    as.character(packageVersion("rdrobust")), "\n")
i <- 1:1200
a <- round(c(0.6180339887498949, 0.4142135623730951) * 2^30) / 2^30   # exact products
u <- ((i * a[2]) %% 1) * 0.998 + 0.001
X <- 100 * ((i * a[1]) %% 1)
C <- ifelse(i %% 2 == 0, 33, 66)
Y <- (1 + 0.02 * X + (X >= C)) * (C == 33) + (0.5 + 0.01 * X + 0.8 * (X >= C)) * (C == 66) + qnorm(u)
Tr <- as.numeric(ifelse(X >= C, u > 0.2, u > 0.85))
YF <- 0.5 + 0.01 * X + 0.9 * Tr + qnorm(((i * a[1] * 3) %% 1) * 0.998 + 0.001)
vec("X", X); vec("C", C); vec("Y", Y); vec("TR", Tr); vec("YF", YF)
out <- function(name, r) {
  vec(paste0(name, "_COEFS"), r$Coefs); vec(paste0(name, "_B"), r$B); vec(paste0(name, "_V"), r$V)
  vec(paste0(name, "_NH"), r$Nh); vec(paste0(name, "_H"), r$H)
  if (!is.null(r$W)) vec(paste0(name, "_W"), r$W)
}
sink(tempfile())
r1 <- rdmc(Y, X, C)
r2 <- rdmc(YF, X, C, fuzzy = Tr)
X2 <- 100 * ((i * a[2]) %% 1)
Y2 <- 1 + 0.02 * X2 + 0.7 * (X2 >= 33) + 0.5 * (X2 >= 66) + qnorm(((i * a[1]) %% 1) * 0.998 + 0.001)
r3 <- rdms(Y2, X2, c(33, 66))
r4 <- rdms(Y2, X2, c(33, 66), rangemat = rbind(c(0, 66), c(33, 100)))
sink()
out("RDMC", r1); out("RDMCF", r2); vec("X2", X2); vec("Y2", Y2); out("RDMS", r3); out("RDMSR", r4)
