# Reference values from RDHonest 1.0.2 for the honest regression discontinuity
# intervals of KernelSmoothing.jl.
RLIB <- commandArgs(trailingOnly = TRUE)[1]
suppressPackageStartupMessages(library(RDHonest, lib.loc = RLIB))
i <- 1:600
phi <- round(0.6180339887498949 * 2^30) / 2^30   # 30 bits, so that the data agree with Julia's
x <- 2 * ((i * phi) %% 1) - 1
y <- 0.5 + 0.8 * x - 0.3 * x^2 + 0.4 * (x >= 0) + 0.3 * sin(7.3 * i)
tr <- as.numeric(ifelse(x >= 0, sin(3.7 * i) > -0.6, sin(3.7 * i) > 0.8))
yf <- 0.5 + 0.8 * x + 0.6 * tr + 0.3 * sin(7.3 * i)
w <- 1 + (i %% 3)
d <- data.frame(y = y, yf = yf, tr = tr, x = x, w = w)
f <- function(v) paste(sprintf("%.17g", v), collapse = ", ")
cat("# generated by rdhonest_golden.R with RDHonest", as.character(packageVersion("RDHonest", lib.loc = RLIB)), "\n")
cat(sprintf("const MROT_SHARP = %.17g\nconst MROT_FUZZY = [%s]\n",
            suppressMessages(RDHonest(y ~ x, data = d, h = 0.5))$coefficients$M,
            f(unlist(suppressMessages(RDHonest(yf | tr ~ x, data = d, h = 0.5))$coefficients[c("M.rf", "M.fs")]))))
cfgs <- list(
  list(M = 1, h = 0.4, se = "nn"), list(M = 1, h = 0.4, se = "EHW"), list(M = 2, h = 0.3, se = "nn", k = "epanechnikov"),
  list(M = 1, se = "nn"), list(M = 1, se = "nn", crit = "FLCI"), list(M = 1, se = "EHW", crit = "OCI"),
  list(M = 0.5, se = "nn", k = "uniform", crit = "FLCI"), list(M = 1, se = "nn", k = "epanechnikov", crit = "MSE"),
  list(se = "nn"), list(M = 1, h = 0.4, se = "nn", sclass = "T"), list(M = 1, se = "nn", sclass = "T", crit = "FLCI"),
  list(M = 1, h = 0.4, se = "EHW", wt = TRUE), list(M = 1, se = "EHW", wt = TRUE),
  list(M = c(1, 0.5), h = 0.5, se = "nn", fuzzy = TRUE), list(M = c(1, 0.5), se = "EHW", fuzzy = TRUE),
  list(M = c(1, 0.5), se = "nn", fuzzy = TRUE, crit = "FLCI", T0 = 1), list(se = "nn", fuzzy = TRUE))
cat("const RDHONEST_RD = [\n")
for (c in cfgs) {
  fz <- isTRUE(c$fuzzy)
  args <- list(formula = if (fz) yf | tr ~ x else y ~ x, data = d, se.method = c$se,
               kern = if (is.null(c$k)) "triangular" else c$k, opt.criterion = if (is.null(c$crit)) "MSE" else c$crit,
               sclass = if (is.null(c$sclass)) "H" else c$sclass, T0 = if (is.null(c$T0)) 0 else c$T0)
  if (!is.null(c$M)) args$M <- c$M
  if (!is.null(c$h)) args$h <- c$h
  if (isTRUE(c$wt)) args$weights <- quote(w)
  r <- suppressMessages(do.call(RDHonest, args))$coefficients
  cat(sprintf("  (fuzzy = %s, M = %s, h = %s, semethod = \"%s\", kernel = \"%s\", criterion = \"%s\", class = \"%s\", T0 = %s, weighted = %s,\n",
              tolower(fz), if (is.null(c$M)) "nothing" else sprintf("[%s]", f(c$M)), if (is.null(c$h)) "nothing" else c$h,
              c$se, args$kern, args$opt.criterion, args$sclass, args$T0, tolower(isTRUE(c$wt))))
  cat(sprintf("   bandwidth = %.17g, estimate = %.17g, se = %.17g, maxbias = %.17g, cv = %.17g, lower = %.17g, upper = %.17g, Mused = %.17g, firststage = %.17g, effobs = %.17g, leverage = %.17g),\n",
              r$bandwidth, r$estimate, r$std.error, r$maximum.bias, r$cv, r$conf.low, r$conf.high, r$M,
              if (fz) r$first.stage else NaN, r$eff.obs, r$leverage))
}
cat("]\n")
