# Reference values from nprobust 1.0.0 with clusters for the tests of KernelSmoothing.jl:
# lprobust with vce = "cr1", "cr2" and "cr3", and lpbwselect with clusters.
RLIB <- commandArgs(trailingOnly = TRUE)[1]
suppressPackageStartupMessages(library(nprobust, lib.loc = RLIB))
i <- 1:400
x <- round((i * 0.6180339887498949) %% 1, 2)
g <- 1 + (i %% 37)                 # 37 clusters spread over x
gx <- 1 + floor(x * 10)            # 11 clusters of neighbouring x
y <- sin(2 * pi * x) + 0.3 * sin(7.3 * i) + 0.4 * sin(3.1 * g)
w <- 1 + (i %% 3)
o <- order(x, i)                   # sorted, since nprobust does not always reorder weights
x <- x[o]; y <- y[o]; g <- g[o]; gx <- gx[o]; w <- w[o]
ev <- c(0, 0.05, 0.3, 0.5, 0.77, 1)
f <- function(v) paste(sprintf("%.17g", v), collapse = ", ")
cat("# generated by cluster_golden.R with nprobust", as.character(packageVersion("nprobust", lib.loc = RLIB)), "\n")
cfgs <- list(
  list(p = 1, d = 0, k = "epa", v = "cr1", h = 0.15, b = 0.15),
  list(p = 1, d = 0, k = "epa", v = "cr2", h = 0.15, b = 0.25),
  list(p = 1, d = 1, k = "tri", v = "cr3", h = 0.2,  b = 0.3),
  list(p = 2, d = 1, k = "uni", v = "cr2", h = 0.25, b = 0.2),
  list(p = 2, d = 0, k = "epa", v = "cr3", h = 0.1,  b = 0.12),
  list(p = 1, d = 0, k = "epa", v = "cr1", h = 0.15, b = 0.2, wt = TRUE),
  list(p = 1, d = 0, k = "epa", v = "cr3", h = 0.15, b = 0.2, wt = TRUE),
  list(p = 1, d = 0, k = "epa", v = "cr1", h = 0.2,  b = 0.2, cx = TRUE),
  list(p = 1, d = 0, k = "epa", v = "cr2", h = 0.2,  b = 0.2, cx = TRUE),
  list(p = 1, d = 0, k = "epa", v = "cr3", h = 0.2,  b = 0.25, cx = TRUE),
  list(p = 1, d = 0, k = "epa", v = "cr2", h = 0.15, b = 0.25, scale = 10))
cat("const LPCLUSTER = [\n")
for (c in cfgs) {
  wt <- isTRUE(c$wt); cx <- isTRUE(c$cx); s <- if (is.null(c$scale)) 1 else c$scale
  args <- list(y = y, x = s * x, eval = s * ev, p = c$p, deriv = c$d, h = s * c$h, b = s * c$b, kernel = c$k,
               vce = c$v, cluster = if (cx) gx else g)
  if (wt) args$weights <- w
  E <- do.call(lprobust, args)$Estimate
  cat(sprintf("  (p = %d, deriv = %d, kernel = \"%s\", vce = \"%s\", h = %s, b = %s, weighted = %s, xclusters = %s, scale = %s,\n",
              c$p, c$d, c$k, c$v, c$h, c$b, tolower(wt), tolower(cx), s))
  cat(sprintf("   N = [%s],\n   tau_us = [%s],\n   tau_bc = [%s],\n   se_us = [%s],\n   se_rb = [%s]),\n",
              f(E[, "N"]), f(E[, "tau.us"]), f(E[, "tau.bc"]), f(E[, "se.us"]), f(E[, "se.rb"])))
}
cat("]\n")
bcfgs <- list(
  list(bw = "mse-dpi",  p = 1, d = 0, k = "epa", v = "cr1"),
  list(bw = "mse-dpi",  p = 1, d = 0, k = "epa", v = "cr2"),
  list(bw = "mse-dpi",  p = 2, d = 1, k = "tri", v = "cr3"),
  list(bw = "mse-dpi",  p = 2, d = 0, k = "epa", v = "cr1"),
  list(bw = "imse-dpi", p = 1, d = 0, k = "epa", v = "cr1"),
  list(bw = "imse-dpi", p = 2, d = 0, k = "tri", v = "cr3"),
  list(bw = "ce-rot",   p = 1, d = 0, k = "epa", v = "cr2"),
  list(bw = "mse-dpi",  p = 1, d = 0, k = "epa", v = "cr1", wt = TRUE))
bev <- c(0, 0.3, 0.5, 1)
cat("const LPBWCLUSTER = [\n")
for (c in bcfgs) {
  wt <- isTRUE(c$wt)
  args <- list(y = y, x = x, eval = bev, p = c$p, deriv = c$d, kernel = c$k, vce = c$v, bwselect = c$bw, cluster = g)
  if (wt) args$weights <- w
  B <- suppressWarnings(do.call(lpbwselect, args))$bws
  cat(sprintf("  (bwselect = \"%s\", p = %d, deriv = %d, kernel = \"%s\", vce = \"%s\", weighted = %s,\n",
              c$bw, c$p, c$d, c$k, c$v, tolower(wt)))
  cat(sprintf("   h = [%s],\n   b = [%s]),\n", f(B[, 2]), f(B[, 3])))
}
cat("]\n")
