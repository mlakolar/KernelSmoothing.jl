# Covariances between points from nprobust 1.0.0's lprobust(covgrid = TRUE) with HC0 variances.
RLIB <- commandArgs(trailingOnly = TRUE)[1]
suppressPackageStartupMessages(library(nprobust, lib.loc = RLIB))
i <- 1:400
x <- round((i * 0.6180339887498949) %% 1, 2)
y <- sin(2 * pi * x) + 0.3 * sin(7.3 * i)
ev <- c(0.3, 0.35, 0.4, 0.7)
f <- function(M) paste0("[", paste(apply(M, 1, function(r) paste(sprintf("%.17g", r), collapse = " ")), collapse = "; "), "]")
cat("# generated by covgrid_golden.R with nprobust", as.character(packageVersion("nprobust", lib.loc = RLIB)), "\n")
for (cfg in list(list(p = 1, d = 0, nm = "P1"), list(p = 2, d = 1, nm = "P2D1"))) {
  r <- lprobust(y, x, eval = ev, p = cfg$p, deriv = cfg$d, h = 0.1, b = 0.15, vce = "hc0", covgrid = TRUE)
  cat(sprintf("const COV_US_%s = %s\n", cfg$nm, f(r$cov.us)))
  cat(sprintf("const COV_RB_%s = %s\n", cfg$nm, f(r$cov.rb)))
}
