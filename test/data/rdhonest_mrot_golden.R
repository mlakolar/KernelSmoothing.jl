# Reference values from RDHonest 1.0.2 for the rule of thumb for M when one side of
# the cutoff has few distinct values of the running variable: k = 1, …, 6 distinct
# values, tied (60 observations) or single, on the left or on the right, with 200
# observations on the other side. RDHonest stops with an error below 5 distinct values.
RLIB <- commandArgs(trailingOnly = TRUE)[1]
.libPaths(c(RLIB, .libPaths()))
suppressPackageStartupMessages(library(RDHonest))
mk <- function(xs) 0.5 + xs + 0.8 * xs^2 + 0.4 * (xs >= 0) + 0.3 * sin(7.3 * seq_along(xs))
xr <- (1:200) / 200 * 0.99
cat("# generated by rdhonest_mrot_golden.R with RDHonest", as.character(packageVersion("RDHonest")), "\n")
cat("const MROT_FEW = [\n")
for (side in c("left", "right")) for (k in 1:6) for (tied in c(TRUE, FALSE)) {
  vals <- (1:k) / (k + 1)
  few <- if (tied) rep(vals, length.out = 60) else vals
  x <- if (side == "left") c(-rev(few), xr) else c(-rev(xr), few)
  M <- tryCatch(suppressMessages(RDHonest(y ~ x, data = data.frame(x = x, y = mk(x)), h = 1))$coefficients$M,
                error = function(e) NA)
  cat(sprintf("  (side = :%s, k = %d, tied = %s, M = %s),\n", side, k, tolower(tied), if (is.na(M)) "nothing" else sprintf("%.17g", M)))
}
cat("]\n")
