# Honest intervals at a point from RDHonest 1.0.2 (Taylor class, EHW standard errors).
RLIB <- commandArgs(trailingOnly = TRUE)[1]
suppressPackageStartupMessages(library(RDHonest, lib.loc = RLIB))
i <- 1:400
x <- round((i * 0.6180339887498949) %% 1, 2)
y <- sin(2 * pi * x) + 0.3 * sin(7.3 * i)
d <- data.frame(y = y, x = x)
cfgs <- list(list(k = "triangular", h = 0.15, x0 = 0.3, M = 40), list(k = "epanechnikov", h = 0.2, x0 = 0.5, M = 20),
             list(k = "uniform", h = 0.1, x0 = 0.75, M = 60), list(k = "triangular", h = 0.2, x0 = 0, M = 30))
cat("# generated by honest_golden.R with RDHonest", as.character(packageVersion("RDHonest", lib.loc = RLIB)), "\n")
cat("const RDHONEST = [\n")
for (c in cfgs) {
  r <- RDHonest(y ~ x, data = d, cutoff = c$x0, M = c$M, kern = c$k, h = c$h, point.inference = TRUE,
                sclass = "T", se.method = "EHW")$coefficients
  cat(sprintf("  (kernel = \"%s\", h = %s, x0 = %s, M = %s, estimate = %.17g, se = %.17g, maxbias = %.17g, cv = %.17g, lower = %.17g, upper = %.17g),\n",
              c$k, c$h, c$x0, c$M, r$estimate, r$std.error, r$maximum.bias, r$cv, r$conf.low, r$conf.high))
}
cat("]\n")
r <- RDHonest(y ~ x, data = d, cutoff = 0.3, M = 40, kern = "triangular", opt.criterion = "FLCI",
              point.inference = TRUE, sclass = "T", se.method = "EHW")$coefficients
cat(sprintf("const RDHONEST_FLCI = (h = %.17g, lower = %.17g, upper = %.17g)\n", r$bandwidth, r$conf.low, r$conf.high))
