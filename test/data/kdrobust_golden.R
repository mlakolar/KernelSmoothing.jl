# Reference values from nprobust 1.0.0's kdrobust and kdbwselect for the tests of KernelSmoothing.jl.
RLIB <- commandArgs(trailingOnly = TRUE)[1]
suppressPackageStartupMessages(library(nprobust, lib.loc = RLIB))
i <- 1:500
x <- round(qnorm((i * 0.6180339887498949) %% 1) + 0.3 * sin(i^2), 2)   # ties
ev <- c(-1, -0.3, 0, 0.5, 1.2)
cfgs <- list(
  list(k = "epa", h = 0.4, b = 0.4),
  list(k = "epa", h = 0.3, b = 0.5),
  list(k = "uni", h = 0.35, b = 0.35),
  list(k = "epa", h = 0.02, b = 0.03),
  list(k = "epa", bw = "imse-dpi"),
  list(k = "epa", bw = "mse-dpi"),
  list(k = "uni", bw = "imse-dpi"),
  list(k = "uni", bw = "mse-dpi"))
cat("# generated by kdrobust_golden.R with nprobust", as.character(packageVersion("nprobust", lib.loc = RLIB)), "\n")
cat("const KDROBUST = [\n")
f <- function(v) paste(sprintf("%.17g", v), collapse = ", ")
for (c in cfgs) {
  args <- list(x = x, eval = ev, kernel = c$k)
  # exact matching: c$b would match the element bw partially
  if (!is.null(c[["h"]])) { args$h <- c[["h"]]; args$b <- c[["b"]] } else args$bwselect <- c[["bw"]]
  E <- do.call(kdrobust, args)$Estimate
  cat(sprintf("  (kernel = \"%s\", h = %s, b = %s, bwselect = \"%s\",\n", c$k,
              if (is.null(c[["h"]])) "nothing" else c[["h"]], if (is.null(c[["b"]])) "nothing" else c[["b"]],
              if (is.null(c[["bw"]])) "" else c[["bw"]]))
  cat(sprintf("   hused = [%s],\n   bused = [%s],\n   N = [%s],\n", f(E[, "h"]), f(E[, "b"]), f(E[, "N"])))
  cat(sprintf("   f_us = [%s],\n   f_bc = [%s],\n   se_us = [%s],\n   se_rb = [%s]),\n", f(E[, "tau.us"]), f(E[, "tau.bc"]), f(E[, "se.us"]), f(E[, "se.rb"])))
}
cat("]\n")
B <- kdbwselect(x = x, eval = ev, bwselect = "imse-dpi")$bws
cat("const KDBW_IMSE_DEFAULT_GRID = (h = ", sprintf("%.17g", B[1, 2]), ", b = ", sprintf("%.17g", B[1, 3]), ")\n")
