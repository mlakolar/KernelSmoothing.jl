# Reference values from lpdensity 3.0.1 for the tests of KernelSmoothing.jl.
RLIB <- commandArgs(trailingOnly = TRUE)[1]
suppressPackageStartupMessages(library(lpdensity, lib.loc = RLIB))
i <- 1:500
xn <- round(qnorm((i * 0.6180339887498949) %% 1) + 0.3 * sin(i^2), 2)    # ties
xe <- -log(1 - (i * 0.7548776662466927) %% 1)                             # exponential: a boundary at 0
w <- 1 + (i %% 3)
f <- function(v) paste(sprintf("%.17g", v), collapse = ", ")
cfgs <- list(
  list(nm = "normal-tri", data = "xn", grid = c(-1, 0, 0.5, 1.5), bw = 0.5, p = 2, v = 1, k = "triangular"),
  list(nm = "exp-boundary", data = "xe", grid = c(0, 0.2, 1), bw = 0.6, p = 2, v = 1, k = "triangular"),
  list(nm = "normal-epa-p1", data = "xn", grid = c(-0.5, 0.7), bw = 0.4, p = 1, v = 1, k = "epanechnikov"),
  list(nm = "normal-uni-deriv", data = "xn", grid = c(-1, 0.5), bw = 0.8, p = 3, v = 2, k = "uniform"),
  list(nm = "normal-weighted", data = "xn", grid = c(-1, 0, 1), bw = 0.5, p = 2, v = 1, k = "triangular", wt = TRUE),
  list(nm = "normal-vector-weighted", data = "xn", grid = c(-1, 0, 1), bw = c(0.6, 0.8, 1.0),
       p = 2, v = 1, k = "triangular", wt = TRUE),
  list(nm = "normal-second-derivative", data = "xn", grid = c(-0.5, 0.5), bw = 1.2,
       p = 4, v = 3, k = "epanechnikov"),
  list(nm = "normal-rot", data = "xn", grid = c(-1.5, -0.5, 0, 0.8), sel = "mse-rot", p = 2, v = 1, k = "triangular"),
  list(nm = "exp-rot", data = "xe", grid = c(0, 0.5, 2), sel = "mse-rot", p = 2, v = 1, k = "epanechnikov"),
  list(nm = "normal-dpi", data = "xn", grid = c(-1.5, -0.5, 0, 0.8), sel = "mse-dpi", p = 2, v = 1, k = "triangular"),
  list(nm = "exp-dpi", data = "xe", grid = c(0, 0.5, 2), sel = "mse-dpi", p = 2, v = 1, k = "epanechnikov"),
  list(nm = "exp-imse", data = "xe", grid = c(0, 0.2, 0.5, 1, 2), sel = "imse-dpi", p = 2, v = 1, k = "triangular"),
  list(nm = "normal-dpi-p1-uni", data = "xn", grid = c(-1, 0.3), sel = "mse-dpi", p = 1, v = 1, k = "uniform"),
  list(nm = "normal-dpi-deriv", data = "xn", grid = c(-1, 0.5), sel = "mse-dpi", p = 3, v = 2, k = "triangular"),
  list(nm = "normal-dpi-weighted", data = "xn", grid = c(-1, 0, 1), sel = "mse-dpi", p = 2, v = 1, k = "triangular",
       wt = TRUE))
cat("# generated by lpdensity_golden.R with lpdensity", as.character(packageVersion("lpdensity", lib.loc = RLIB)), "\n")
cat("const LPDENSITY = [\n")
for (c in cfgs) {
  x <- get(c[["data"]])
  args <- list(data = x, grid = c[["grid"]], p = c[["p"]], v = c[["v"]], kernel = c[["k"]])
  if (!is.null(c[["bw"]])) args$bw <- c[["bw"]] else args$bwselect <- c[["sel"]]
  if (!is.null(c[["wt"]])) args$Pweights <- w
  r <- do.call(lpdensity, args)
  E <- r$Estimate
  cat(sprintf("  (name = \"%s\", data = :%s, p = %d, v = %d, kernel = \"%s\", weighted = %s, selection = \"%s\",\n",
              c[["nm"]], c[["data"]], c[["p"]], c[["v"]], c[["k"]], tolower(!is.null(c[["wt"]])),
              if (is.null(c[["sel"]])) "" else c[["sel"]]))
  cat(sprintf("   grid = [%s], bw = [%s], nh = [%s], nhu = [%s],\n", f(E[, "grid"]), f(E[, "bw"]), f(E[, "nh"]), f(E[, "nhu"])))
  cat(sprintf("   f_p = [%s], f_q = [%s], se_p = [%s], se_q = [%s],\n", f(E[, "f_p"]), f(E[, "f_q"]), f(E[, "se_p"]), f(E[, "se_q"])))
  cat(sprintf("   cov_p = [%s],\n", paste(apply(r$CovMat_p, 1, function(row) paste(sprintf("%.17g", row), collapse = " ")), collapse = "; ")))
  cat(sprintf("   cov_q = [%s]),\n", paste(apply(r$CovMat_q, 1, function(row) paste(sprintf("%.17g", row), collapse = " ")), collapse = "; ")))
}
cat("]\n")
