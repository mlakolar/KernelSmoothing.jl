# Reference values from the R package evmix for the boundary-corrected density
# estimates of KernelSmoothing.jl. The library with evmix is the first argument, or
# on the library path.
RLIB <- commandArgs(trailingOnly = TRUE)[1]
if (!is.na(RLIB)) .libPaths(c(RLIB, .libPaths()))
suppressPackageStartupMessages(library(evmix))
f <- function(v) paste(sprintf("%.17g", v), collapse = ", ")
vec <- function(name, v) cat("const ", name, " = [", f(v), "]\n", sep = "")
cat("# generated by bounded_golden.R with evmix", as.character(packageVersion("evmix")), "and", R.version.string, "\n")
i <- 1:150
phi <- round(0.6180339887498949 * 2^30) / 2^30   # exact products
u <- ((i * phi) %% 1) * 0.998 + 0.001
x <- qgamma(u, 2, 1)       # on (0, Inf), a density that vanishes at 0
y <- qbeta(u, 2, 3)        # on (0, 1)
vec("XG", x); vec("YB", y)
px <- c(0, 0.05, 0.2, 0.5, 1, 2, 3.5, 6); py <- c(0, 0.02, 0.1, 0.3, 0.5, 0.7, 0.95, 1)
vec("PX", px); vec("PY", py)
# reflection at 0
vec("REFL_GAUSS", dbckden(px, x, bw = 0.3, kernel = "gaussian", bcmethod = "reflect"))
vec("REFL_GAUSS_CDF", pbckden(px, x, bw = 0.3, kernel = "gaussian", bcmethod = "reflect"))
vec("REFL_EPAN", dbckden(px, x, lambda = 0.5, kernel = "epanechnikov", bcmethod = "reflect"))
vec("REFL_EPAN_CDF", pbckden(px, x, lambda = 0.5, kernel = "epanechnikov", bcmethod = "reflect"))
# beta kernels on [0, 1] and gamma kernels on [0, Inf), without and with renormalization
for (m in c("beta1", "beta2")) {
  vec(paste0(toupper(m), "_RAW"), dbckden(py, y, lambda = 0.05, bcmethod = m, xmax = 1, proper = FALSE))
  vec(paste0(toupper(m)), dbckden(py, y, lambda = 0.05, bcmethod = m, xmax = 1, proper = TRUE))
  vec(paste0(toupper(m), "_CDF"), pbckden(py[2:7], y, lambda = 0.05, bcmethod = m, xmax = 1, proper = TRUE))
}
for (m in c("gamma1", "gamma2")) {
  vec(paste0(toupper(m), "_RAW"), dbckden(px, x, lambda = 0.1, bcmethod = m, proper = FALSE))
  vec(paste0(toupper(m)), dbckden(px, x, lambda = 0.1, bcmethod = m, proper = TRUE))
  vec(paste0(toupper(m), "_CDF"), pbckden(px[2:8], x, lambda = 0.1, bcmethod = m, proper = TRUE))
}
# the log transformation, of x + 1e-12: our support (-1e-12, Inf)
vec("LOGT", dbckden(px[2:8], x, bw = 0.3, kernel = "gaussian", bcmethod = "logtrans", offset = 1e-12))
vec("LOGT_CDF", pbckden(px[2:8], x, bw = 0.3, kernel = "gaussian", bcmethod = "logtrans", offset = 1e-12))
