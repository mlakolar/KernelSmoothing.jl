# Reference values from rddensity 3.0 for the manipulation tests of KernelSmoothing.jl.
RLIB <- commandArgs(trailingOnly = TRUE)[1]
suppressPackageStartupMessages(library(rddensity, lib.loc = RLIB))
i <- 1:600
# a constant of 30 bits, so that the products below are exact: R's products of these
# doubles can differ from Julia's in the last bit, which moved an observation across
# the edge of a window of the binomial test
phi <- round(0.6180339887498949 * 2^30) / 2^30
x <- 2 * ((i * phi) %% 1) - 1                   # no ties
xj <- ifelse(x < 0, x, x^2)                     # a density that jumps at 0
xm <- round(10 * x) / 10                        # mass points (round(x, 1) differs from Julia)
f <- function(v) paste(sprintf("%.17g", v), collapse = ", ")
cat("# generated by rddensity_golden.R with rddensity", as.character(packageVersion("rddensity", lib.loc = RLIB)), "\n")
cfgs <- list(
  list(x = "x"), list(x = "xj"),
  list(x = "x", bw = "each"), list(x = "x", bw = "diff"), list(x = "x", bw = "sum"),
  list(x = "xj", vce = "plugin"),
  list(x = "x", fit = "restricted"), list(x = "xj", fit = "restricted", vce = "plugin"),
  list(x = "x", fit = "restricted", bw = "diff"),
  list(x = "x", p = 1), list(x = "xj", p = 3),
  list(x = "x", k = "uniform"), list(x = "xj", k = "epanechnikov"),
  list(x = "x", h = 0.4), list(x = "xj", h = c(0.3, 0.5)), list(x = "xj", h = c(0.3, 0.5), vce = "plugin"),
  list(x = "xm"), list(x = "xm", mp = FALSE),
  list(x = "x", c = 0.2))
cat("const RDDENSITY = [\n")
for (a in cfgs) {
  args <- list(X = get(a$x), c = if (is.null(a$c)) 0 else a$c, p = if (is.null(a$p)) 2 else a$p,
               bwselect = if (is.null(a$bw)) "comb" else a$bw, vce = if (is.null(a$vce)) "jackknife" else a$vce,
               fitselect = if (is.null(a$fit)) "unrestricted" else a$fit, kernel = if (is.null(a$k)) "triangular" else a$k,
               massPoints = if (is.null(a$mp)) TRUE else a$mp)
  if (!is.null(a$h)) args$h <- a$h
  r <- suppressWarnings(do.call(rddensity, args))
  jk <- args$vce == "jackknife"
  sd <- if (jk) r$sd_jk else r$sd_asy
  t <- if (jk) r$test$t_jk else r$test$t_asy
  pv <- if (jk) r$test$p_jk else r$test$p_asy
  cat(sprintf("  (x = \"%s\", c = %s, p = %d, bwselect = \"%s\", vce = \"%s\", fitselect = \"%s\", kernel = \"%s\", masspoints = %s, h = %s,\n",
              a$x, args$c, args$p, args$bwselect, args$vce, args$fitselect, args$kernel, tolower(args$massPoints),
              if (is.null(a$h)) "nothing" else sprintf("[%s]", f(rep(a$h, length.out = 2)))))
  cat(sprintf("   hused = [%s], nh = [%s],\n   hat = [%s],\n   sd = [%s],\n   t = %.17g, pvalue = %.17g,\n",
              f(c(r$h$left, r$h$right)), f(c(r$N$eff_left, r$N$eff_right)), f(unlist(r$hat)), f(unlist(sd)), t, pv))
  cat(sprintf("   bino_left = [%s], bino_right = [%s], bino_nl = [%s], bino_nr = [%s], bino_p = [%s]",
              f(r$bino$LeftWindow), f(r$bino$RightWindow), f(r$bino$LeftN), f(r$bino$RightN), f(r$bino$pval)))
  if (is.null(a$h)) {
    b <- suppressWarnings(rdbwdensity(X = get(a$x), c = args$c, p = args$p, fitselect = args$fitselect, kernel = args$kernel,
                                      vce = args$vce, massPoints = args$massPoints))$h
    cat(sprintf(",\n   bw = [%s]", f(b[, 1])))
  }
  cat("),\n")
}
cat("]\n")
