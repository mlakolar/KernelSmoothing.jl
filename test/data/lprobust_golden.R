# Reference values from nprobust 1.0.0 for the local polynomial tests of KernelSmoothing.jl.
RLIB <- commandArgs(trailingOnly = TRUE)[1]
suppressPackageStartupMessages(library(nprobust, lib.loc = RLIB))
i <- 1:400
x <- round((i * 0.6180339887498949) %% 1, 2)        # ties: 101 distinct values
y <- sin(2 * pi * x) + 0.3 * sin(7.3 * i)
w <- 1 + (i %% 3)
ev <- c(0, 0.05, 0.3, 0.5, 0.77, 1)
cfgs <- list(
  list(p = 1, d = 0, k = "epa", v = "nn",  h = 0.15, b = 0.15, wt = FALSE),
  list(p = 1, d = 0, k = "epa", v = "hc0", h = 0.15, b = 0.25, wt = FALSE),
  list(p = 1, d = 1, k = "tri", v = "hc1", h = 0.2,  b = 0.3,  wt = FALSE),
  list(p = 2, d = 1, k = "uni", v = "hc2", h = 0.2,  b = 0.2,  wt = FALSE),
  list(p = 0, d = 0, k = "epa", v = "hc3", h = 0.1,  b = 0.12, wt = FALSE),
  list(p = 2, d = 0, k = "epa", v = "nn",  h = 0.03, b = 0.04, wt = FALSE),
  list(p = 1, d = 0, k = "epa", v = "hc1", h = 0.15, b = 0.2,  wt = TRUE),
  list(p = 2, d = 2, k = "epa", v = "nn",  h = 0.25, b = 0.3,  wt = TRUE),
  list(p = 1, d = 0, k = "tri", v = "nn",  h = 0.4,  b = 0.25, wt = FALSE))
cat("# generated by lprobust_golden.R with nprobust", as.character(packageVersion("nprobust", lib.loc = RLIB)), "\n")
cat("const LPROBUST = [\n")
for (c in cfgs) {
  args <- list(y = y, x = x, eval = ev, p = c$p, deriv = c$d, h = c$h, b = c$b, kernel = c$k, vce = c$v)
  if (c$wt) args$weights <- w
  E <- do.call(lprobust, args)$Estimate
  f <- function(v) paste(sprintf("%.17g", v), collapse = ", ")
  cat(sprintf("  (p = %d, deriv = %d, kernel = \"%s\", vce = \"%s\", h = %s, b = %s, weighted = %s,\n", c$p, c$d, c$k, c$v, c$h, c$b, tolower(c$wt)))
  cat(sprintf("   hused = [%s],\n   bused = [%s],\n   N = [%s],\n", f(E[, "h"]), f(E[, "b"]), f(E[, "N"])))
  cat(sprintf("   tau_us = [%s],\n   tau_bc = [%s],\n   se_us = [%s],\n   se_rb = [%s]),\n", f(E[, "tau.us"]), f(E[, "tau.bc"]), f(E[, "se.us"]), f(E[, "se.rb"])))
}
cat("]\n")
