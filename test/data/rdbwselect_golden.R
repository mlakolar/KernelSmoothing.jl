# Reference bandwidths from rdrobust 4.1.1's rdbwselect, and rdrobust fits with its
# default bandwidths, for the tests of KernelSmoothing.jl.
RLIB <- commandArgs(trailingOnly = TRUE)[1]
suppressPackageStartupMessages(library(rdrobust, lib.loc = RLIB))
i <- 1:600
x <- round(2 * ((i * 0.6180339887498949) %% 1) - 1, 3)
xm <- round(10 * x) / 10                          # mass points: 21 distinct values (round(x, 1) differs from Julia)
z1 <- cos(2.3 * i) + 0.5 * x
z2 <- sin(1.1 * i)
y <- 0.5 + 0.8 * x - 0.3 * x^2 + 0.4 * (x >= 0) + 0.3 * sin(7.3 * i)
yc <- y + 0.5 * z1 - 0.3 * z2
tr <- as.numeric(ifelse(x >= 0, sin(3.7 * i) > -0.6, sin(3.7 * i) > 0.8))
yf <- 0.5 + 0.8 * x + 0.6 * tr + 0.3 * sin(7.3 * i)
g <- 1 + (i %% 50)
w <- 1 + (i %% 3)
f <- function(v) paste(sprintf("%.17g", v), collapse = ", ")
cat("# generated by rdbwselect_golden.R with rdrobust", as.character(packageVersion("rdrobust", lib.loc = RLIB)), "\n")
sel <- c("mserd", "msetwo", "msesum", "msecomb1", "msecomb2", "cerrd", "certwo", "cersum", "cercomb1", "cercomb2")
cfgs <- c(lapply(sel, function(s) list(bw = s, y = "y", x = "x", p = 1, d = 0, k = "tri", v = "nn")), list(
  list(bw = "mserd", y = "y",  x = "x",  p = 1, d = 0, k = "epa", v = "hc1"),
  list(bw = "mserd", y = "y",  x = "x",  p = 2, d = 0, k = "uni", v = "hc3"),
  list(bw = "msetwo", y = "y", x = "x",  p = 1, d = 0, k = "tri", v = "hc2"),
  list(bw = "mserd", y = "y",  x = "x",  p = 2, d = 1, k = "tri", v = "nn"),
  list(bw = "mserd", y = "yf", x = "x",  p = 1, d = 0, k = "tri", v = "nn", fuzzy = TRUE),
  list(bw = "msetwo", y = "yf", x = "x", p = 1, d = 0, k = "tri", v = "hc1", fuzzy = TRUE),
  list(bw = "mserd", y = "yc", x = "x",  p = 1, d = 0, k = "tri", v = "nn", covs = TRUE),
  list(bw = "mserd", y = "yc", x = "x",  p = 1, d = 0, k = "tri", v = "hc0", covs = TRUE, fuzzy = TRUE),
  list(bw = "mserd", y = "y",  x = "x",  p = 1, d = 0, k = "tri", v = "hc1", wt = TRUE),
  list(bw = "mserd", y = "y",  x = "x",  p = 1, d = 0, k = "tri", v = "cr1", cl = TRUE),
  list(bw = "cerrd", y = "y",  x = "x",  p = 1, d = 0, k = "tri", v = "cr1", cl = TRUE),
  list(bw = "mserd", y = "y",  x = "x",  p = 1, d = 0, k = "tri", v = "cr2", cl = TRUE),
  list(bw = "msetwo", y = "y", x = "x",  p = 1, d = 0, k = "tri", v = "cr3", cl = TRUE),
  list(bw = "mserd", y = "y",  x = "xm", p = 1, d = 0, k = "tri", v = "nn"),
  list(bw = "mserd", y = "y",  x = "xm", p = 1, d = 0, k = "tri", v = "nn", mp = "off"),
  list(bw = "msetwo", y = "y", x = "x",  p = 1, d = 0, k = "tri", v = "nn", bwcheck = 50)))
cat("const RDBWSELECT = [\n")
for (c in cfgs) {
  args <- list(y = get(c$y), x = get(c$x), p = c$p, deriv = c$d, kernel = c$k, vce = c$v, bwselect = c$bw)
  if (isTRUE(c$fuzzy)) args$fuzzy <- tr
  if (isTRUE(c$covs)) args$covs <- cbind(z1, z2)
  if (isTRUE(c$wt)) args$weights <- w
  if (isTRUE(c$cl)) args$cluster <- g
  if (!is.null(c$mp)) args$masspoints <- c$mp
  if (!is.null(c$bwcheck)) args$bwcheck <- c$bwcheck
  B <- suppressWarnings(do.call(rdbwselect, args))$bws
  cat(sprintf("  (bwselect = \"%s\", y = \"%s\", x = \"%s\", p = %d, deriv = %d, kernel = \"%s\", vce = \"%s\", fuzzy = %s, covs = %s, weighted = %s, clustered = %s, masspoints = \"%s\", bwcheck = %s,\n",
              c$bw, c$y, c$x, c$p, c$d, c$k, c$v, tolower(isTRUE(c$fuzzy)), tolower(isTRUE(c$covs)), tolower(isTRUE(c$wt)), tolower(isTRUE(c$cl)),
              if (is.null(c$mp)) "adjust" else c$mp, if (is.null(c$bwcheck)) "nothing" else c$bwcheck))
  cat(sprintf("   bws = [%s]),\n", f(B[1, ])))
}
cat("]\n")
# full fits with the default bandwidths
fcfgs <- list(list(y = "y", v = "nn"), list(y = "yf", v = "nn", fuzzy = TRUE), list(y = "y", v = "cr1", cl = TRUE),
              list(y = "yc", v = "hc1", covs = TRUE))
cat("const RDDEFAULT = [\n")
for (c in fcfgs) {
  args <- list(y = get(c$y), x = x, vce = c$v)
  if (isTRUE(c$fuzzy)) args$fuzzy <- tr
  if (isTRUE(c$covs)) args$covs <- cbind(z1, z2)
  if (isTRUE(c$cl)) args$cluster <- g
  r <- suppressWarnings(do.call(rdrobust, args))
  cat(sprintf("  (y = \"%s\", vce = \"%s\", fuzzy = %s, covs = %s, clustered = %s, h = [%s], b = [%s], coef = [%s], se = [%s]),\n",
              c$y, c$v, tolower(isTRUE(c$fuzzy)), tolower(isTRUE(c$covs)), tolower(isTRUE(c$cl)),
              f(r$bws[1, ]), f(r$bws[2, ]), f(r$coef), f(r$se)))
}
cat("]\n")
