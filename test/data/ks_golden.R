# Reference values from the R package ks for the multivariate kernel density
# estimates of KernelSmoothing.jl. The library with ks is the first argument, or on
# the library path. Exact computations throughout: binned = FALSE.
RLIB <- commandArgs(trailingOnly = TRUE)[1]
if (!is.na(RLIB)) .libPaths(c(RLIB, .libPaths()))
suppressPackageStartupMessages(library(ks))
f <- function(v) paste(sprintf("%.17g", v), collapse = ", ")
mat <- function(name, m) cat("const ", name, " = reshape([", f(m), "], ", nrow(m), ", ", ncol(m), ")\n", sep = "")
vec <- function(name, v) cat("const ", name, " = [", f(v), "]\n", sep = "")
# quasi-random normal scores, skewed and correlated; the constants have 30 bits, so
# that the products are exact
sample <- function(n, d) {
  i <- 1:n
  a <- round(c(0.6180339887498949, 0.4142135623730951, 0.7320508075688772) * 2^30) / 2^30
  z <- sapply(1:d, function(k) qnorm(((i * a[k]) %% 1) * 0.998 + 0.001))
  x <- z
  x[, 2] <- 0.6 * z[, 1] + 0.8 * z[, 2] + 0.3 * z[, 1]^2
  if (d >= 3) x[, 3] <- 0.5 * z[, 3] - 0.4 * z[, 1] + 0.2 * abs(z[, 2])
  x
}
cat("# generated by ks_golden.R with ks", as.character(packageVersion("ks")), "and", R.version.string, "\n")
K <- asNamespace("ks")
for (d in 2:3) {
  n <- if (d == 2) 200 else 150
  x <- sample(n, d)
  xs <- pre.sphere(x)
  s <- function(name) paste0(name, d)
  mat(s("X"), t(x))   # the observations as columns
  mat(s("HNS"), Hns(x))
  if (d == 2) mat(s("HNSDIAG"), Hns.diag(x))   # for d = 3, ks's Hns.diag is not the optimal diagonal
  mat(s("HPI1_"), Hpi(x, pilot = "samse", nstage = 1, binned = FALSE))
  mat(s("HPI2_"), Hpi(x, pilot = "samse", nstage = 2, binned = FALSE))
  mat(s("HPIDIAG"), Hpi.diag(x, pilot = "samse", binned = FALSE))
  mat(s("HLSCVDIAG"), Hlscv.diag(x, binned = FALSE))
  r <- Hlscv(x, binned = FALSE, amise = TRUE)
  mat(s("HLSCV"), r$H); vec(s("LSCVMIN"), r$LSCV)
  mat(s("HSCV"), Hscv(x, pilot = "samse", binned = FALSE))   # a different pilot; not compared exactly
  # the functionals of order 4 for G = 0.3 I, in the order of vec(D^⊗4)
  k <- kfe(x, G = diag(d) * 0.3, deriv.order = 4, binned = FALSE)
  vec(s("KFE4_"), k$psir); mat(s("KFE4IND"), t(k$deriv.ind))
  # the criteria at fixed matrices
  vec(s("SCVAT"), K$scv.mat(xs, diag(d) * 0.2, diag(d) * 0.3))
  vec(s("LSCVAT"), K$lscv.mat(x, Hns(x)))
  # the density at observations and at off-sample points, without and with weights
  ev <- rbind(x[c(1, 50, 100), ], matrix(c(0.5, -1, rep(0.25, d - 2), -2, 3, rep(-0.5, d - 2)), 2, d, byrow = TRUE))
  w <- 1 + (1:n %% 3)
  mat(s("EVAL"), t(ev))
  vec(s("KDE"), kde(x, H = Hns(x), eval.points = ev, binned = FALSE)$estimate)
  vec(s("KDEW"), kde(x, H = Hns(x), eval.points = ev, binned = FALSE, w = w * n / sum(w))$estimate)
}
