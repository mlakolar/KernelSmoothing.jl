# Reference bandwidths from R's stats::bw.SJ with fine binning and a tight tolerance.
i <- 1:300
x <- qnorm((i * 0.6180339887498949) %% 1) + 0.5 * (i %% 3 == 0) * 2.5   # a skewed mixture
x2 <- round(x, 1)                                                   # with ties
f <- function(v) sprintf("%.15g", v)
cat("# generated by sj_golden.R with", R.version.string, "\n")
cat("const SJ_STE = ", f(bw.SJ(x, nb = 2000000L, tol = 1e-12)), "\n")
cat("const SJ_DPI = ", f(bw.SJ(x, nb = 2000000L, method = "dpi")), "\n")
cat("const SJ_STE_TIES = ", f(bw.SJ(x2, nb = 200000L, tol = 1e-12)), "\n")
cat("const NRD0 = ", f(bw.nrd0(x)), "\n")
