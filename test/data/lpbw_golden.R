# Reference bandwidths from nprobust 1.0.0's lpbwselect for the tests of KernelSmoothing.jl.
RLIB <- commandArgs(trailingOnly = TRUE)[1]
suppressPackageStartupMessages(library(nprobust, lib.loc = RLIB))
i <- 1:400
x <- round((i * 0.6180339887498949) %% 1, 2)
y <- sin(2 * pi * x) + 0.3 * sin(7.3 * i)
o <- order(x, i)                  # sorted, for weights: nprobust does not reorder them
xs <- x[o]; ys <- y[o]; ws <- (1 + (i %% 3))[o]
ev <- c(0, 0.3, 0.5, 1)
cfgs <- list(
  list(bw = "mse-dpi",  p = 1, d = 0, k = "epa", v = "nn"),
  list(bw = "mse-dpi",  p = 1, d = 0, k = "tri", v = "hc1"),
  list(bw = "mse-dpi",  p = 2, d = 1, k = "uni", v = "hc3"),
  list(bw = "mse-dpi",  p = 0, d = 0, k = "epa", v = "nn"),
  list(bw = "mse-dpi",  p = 2, d = 0, k = "epa", v = "hc0"),
  list(bw = "mse-dpi",  p = 0, d = 0, k = "epa", v = "hc2", interior = TRUE),
  list(bw = "mse-dpi",  p = 1, d = 0, k = "epa", v = "nn", bwregul = 0),
  list(bw = "imse-dpi", p = 1, d = 0, k = "epa", v = "nn"),
  list(bw = "imse-dpi", p = 0, d = 0, k = "tri", v = "hc2"),
  list(bw = "ce-rot",   p = 1, d = 0, k = "epa", v = "nn"),
  list(bw = "ce-rot",   p = 2, d = 0, k = "epa", v = "hc1"),
  list(bw = "mse-dpi",  p = 1, d = 0, k = "epa", v = "nn", w = TRUE))
cat("# generated by lpbw_golden.R with nprobust", as.character(packageVersion("nprobust", lib.loc = RLIB)), "\n")
cat("const LPBWSELECT = [\n")
f <- function(v) paste(sprintf("%.17g", v), collapse = ", ")
for (c in cfgs) {
  wt <- !is.null(c$w); interior <- !is.null(c$interior); regul <- if (is.null(c$bwregul)) 1 else c$bwregul
  args <- list(y = if (wt) ys else y, x = if (wt) xs else x, eval = ev, p = c$p, deriv = c$d,
               kernel = c$k, vce = c$v, bwselect = c$bw, interior = interior, bwregul = regul)
  if (wt) args$weights <- ws
  B <- suppressWarnings(do.call(lpbwselect, args))$bws
  cat(sprintf("  (bwselect = \"%s\", p = %d, deriv = %d, kernel = \"%s\", vce = \"%s\", interior = %s, regul = %s, weighted = %s,\n",
              c$bw, c$p, c$d, c$k, c$v, tolower(interior), regul, tolower(wt)))
  cat(sprintf("   h = [%s],\n   b = [%s]),\n", f(B[, 2]), f(B[, 3])))
}
cat("]\n")
