# Reference values from rdlocrand's rdrandinf for the local randomization inference of
# KernelSmoothing.jl. The library with rdlocrand is the first argument, or on the
# library path.
RLIB <- commandArgs(trailingOnly = TRUE)[1]
if (!is.na(RLIB)) .libPaths(c(RLIB, .libPaths()))
suppressPackageStartupMessages(library(rdlocrand))
f <- function(v) paste(sprintf("%.17g", v), collapse = ", ")
vec <- function(name, v) cat("const ", name, " = [", f(v), "]\n", sep = "")
cat("# generated by rdlocrand_golden.R with rdlocrand", as.character(packageVersion("rdlocrand")), "\n")
i <- 1:400
a <- round(c(0.6180339887498949, 0.4142135623730951) * 2^30) / 2^30   # exact products
x <- 2 * ((i * a[1]) %% 1) - 1
y <- 0.5 + 0.3 * x + 0.4 * (x >= 0) + 0.5 * qnorm(((i * a[2]) %% 1) * 0.998 + 0.001)
yt <- round(y, 1)   # with ties
vec("X", x); vec("Y", y); vec("YT", yt)
# (outcome, cutoff, wl, wr, nulltau)
cases <- list(list("Y", 0, -0.2, 0.2, 0), list("Y", 0, -0.15, 0.25, 0.4), list("YT", 0, -0.3, 0.3, 0),
              list("Y", 0, -0.6, 0.6, 0), list("YT", 0, -0.6, 0.6, 0.2), list("Y", 0.1, 0, 0.3, 0))
cat("const RDLOCRAND = [\n")
for (cs in cases) {
  yy <- if (cs[[1]] == "Y") y else yt
  sink(tempfile())
  r <- rdrandinf(yy, x, cutoff = cs[[2]], wl = cs[[3]], wr = cs[[4]], nulltau = cs[[5]], statistic = "all",
                 reps = 20000)
  sink()
  ss <- r$sumstats
  cat("  (y = :", cs[[1]], ", cutoff = ", cs[[2]], ", window = (", cs[[3]], ", ", cs[[4]], "), nulltau = ", cs[[5]],
      ",\n   n = (", ss[2, 1], ", ", ss[2, 2], "), means = (", f(ss[3, 1]), ", ", f(ss[3, 2]), "), sds = (",
      f(ss[4, 1]), ", ", f(ss[4, 2]), "),\n   observed = [", f(r$obs.stat), "],\n   asymptotic = [",
      f(r$asy.pvalue), "],\n   pvalue = [", f(r$p.value), "], reps = 20000),\n", sep = "")
}
cat("]\n")
sink(tempfile()); r <- rdrandinf(y, x, wl = -0.2, wr = 0.2); sink()
cat("# the default statistic\nconst DEFAULT_STAT = [", f(c(r$obs.stat, r$asy.pvalue)), "]\n", sep = "")
