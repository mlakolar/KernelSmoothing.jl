# Reference values from rdrobust 4.1.1 with given bandwidths for the tests of
# KernelSmoothing.jl: sharp, fuzzy and kink designs, covariates, weights and clusters.
RLIB <- commandArgs(trailingOnly = TRUE)[1]
suppressPackageStartupMessages(library(rdrobust, lib.loc = RLIB))
i <- 1:600
x <- round(2 * ((i * 0.6180339887498949) %% 1) - 1, 3)
z1 <- cos(2.3 * i) + 0.5 * x
z2 <- sin(1.1 * i)
y <- 0.5 + 0.8 * x - 0.3 * x^2 + 0.4 * (x >= 0) + 0.3 * sin(7.3 * i)
yc <- y + 0.5 * z1 - 0.3 * z2
tr <- as.numeric(ifelse(x >= 0, sin(3.7 * i) > -0.6, sin(3.7 * i) > 0.8))
yf <- 0.5 + 0.8 * x + 0.6 * tr + 0.3 * sin(7.3 * i)
g <- 1 + (i %% 50)
w <- 1 + (i %% 3)
f <- function(v) paste(sprintf("%.17g", v), collapse = ", ")
cat("# generated by rdrobust_golden.R with rdrobust", as.character(packageVersion("rdrobust", lib.loc = RLIB)), "\n")
cfgs <- list(
  list(y = "y",  p = 1, d = 0, k = "tri", v = "nn",  h = 0.3,  b = 0.5),
  list(y = "y",  p = 1, d = 0, k = "epa", v = "hc0", h = 0.3,  b = 0.3),
  list(y = "y",  p = 2, d = 0, k = "uni", v = "hc1", h = c(0.4, 0.5), b = c(0.6, 0.7)),
  list(y = "y",  p = 1, d = 0, k = "tri", v = "hc2", h = 0.3,  b = 0.45),
  list(y = "y",  p = 1, d = 0, k = "tri", v = "hc3", h = 0.35, b = 0.5),
  list(y = "y",  p = 2, d = 1, k = "tri", v = "nn",  h = 0.5,  b = 0.7),
  list(y = "yf", p = 1, d = 0, k = "tri", v = "nn",  h = 0.4,  b = 0.6, fuzzy = TRUE),
  list(y = "yf", p = 1, d = 0, k = "tri", v = "hc1", h = 0.4,  b = 0.5, fuzzy = TRUE),
  list(y = "yc", p = 1, d = 0, k = "tri", v = "nn",  h = 0.4,  b = 0.6, covs = TRUE),
  list(y = "yc", p = 1, d = 0, k = "tri", v = "hc2", h = 0.4,  b = 0.6, covs = TRUE, fuzzy = TRUE),
  list(y = "y",  p = 1, d = 0, k = "tri", v = "hc1", h = 0.3,  b = 0.5, wt = TRUE),
  list(y = "y",  p = 1, d = 0, k = "tri", v = "cr1", h = 0.3,  b = 0.5, cl = TRUE),
  list(y = "y",  p = 1, d = 0, k = "tri", v = "cr2", h = 0.3,  b = 0.3, cl = TRUE),
  list(y = "y",  p = 1, d = 0, k = "tri", v = "cr2", h = 0.3,  b = 0.5, cl = TRUE),
  list(y = "y",  p = 1, d = 0, k = "tri", v = "cr3", h = 0.3,  b = 0.5, cl = TRUE),
  list(y = "y",  p = 1, d = 0, k = "tri", v = "cr3", h = 0.3,  b = 0.3, cl = TRUE),
  list(y = "yf", p = 1, d = 0, k = "tri", v = "cr1", h = 0.4,  b = 0.6, cl = TRUE, fuzzy = TRUE),
  list(y = "yc", p = 3, d = 2, k = "epa", v = "hc0", h = 0.7,  b = 0.9, covs = TRUE),
  # kink designs: the jump in the slope, sharp and fuzzy (Card, Lee, Pei and Weber 2015)
  list(y = "y",  p = 1, d = 1, k = "tri", v = "hc0", h = 0.5,  b = 0.7),
  list(y = "yf", p = 2, d = 1, k = "tri", v = "nn",  h = 0.5,  b = 0.7, fuzzy = TRUE),
  list(y = "yf", p = 2, d = 1, k = "epa", v = "hc1", h = c(0.5, 0.6), b = c(0.7, 0.8), fuzzy = TRUE))
cat("const RDROBUST = [\n")
for (c in cfgs) {
  args <- list(y = get(c$y), x = x, p = c$p, deriv = c$d, h = c$h, b = c$b, kernel = c$k, vce = c$v)
  if (isTRUE(c$fuzzy)) args$fuzzy <- tr
  if (isTRUE(c$covs)) args$covs <- cbind(z1, z2)
  if (isTRUE(c$wt)) args$weights <- w
  if (isTRUE(c$cl)) args$cluster <- g
  r <- suppressWarnings(do.call(rdrobust, args))
  hh <- rep(c$h, length.out = 2); bb <- rep(c$b, length.out = 2)
  cat(sprintf("  (y = \"%s\", p = %d, deriv = %d, kernel = \"%s\", vce = \"%s\", h = [%s], b = [%s], fuzzy = %s, covs = %s, weighted = %s, clustered = %s,\n",
              c$y, c$p, c$d, c$k, c$v, f(hh), f(bb), tolower(isTRUE(c$fuzzy)), tolower(isTRUE(c$covs)), tolower(isTRUE(c$wt)), tolower(isTRUE(c$cl))))
  cat(sprintf("   N_h = [%s], N_b = [%s],\n   coef = [%s],\n   se = [%s],\n   tau_lr = [%s],\n   bias = [%s]",
              f(r$N_h), f(r$N_b), f(r$coef), f(r$se), f(r$tau_cl), f(r$bias)))
  if (isTRUE(c$fuzzy)) cat(sprintf(",\n   tau_T = [%s],\n   se_T = [%s]", f(r$tau_T), f(r$se_T)))
  if (isTRUE(c$covs)) cat(sprintf(",\n   gamma = [%s]", f(r$coef_covs)))
  cat("),\n")
}
cat("]\n")
