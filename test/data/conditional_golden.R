# Reference values from the R packages np and quantreg for the conditional density
# estimates and the local quantile regression of KernelSmoothing.jl. The library
# with the packages is the first argument, or on the library path.
RLIB <- commandArgs(trailingOnly = TRUE)[1]
if (!is.na(RLIB)) .libPaths(c(RLIB, .libPaths()))
suppressPackageStartupMessages({ library(np); library(quantreg) })
options(np.messages = FALSE)
f <- function(v) paste(sprintf("%.17g", v), collapse = ", ")
vec <- function(name, v) cat("const ", name, " = [", f(v), "]\n", sep = "")
cat("# generated by conditional_golden.R with np", as.character(packageVersion("np")), "and quantreg",
    as.character(packageVersion("quantreg")), "and", R.version.string, "\n")
i <- 1:150
a <- round(c(0.6180339887498949, 0.4142135623730951) * 2^30) / 2^30   # exact products
u1 <- ((i * a[1]) %% 1) * 0.998 + 0.001; u2 <- ((i * a[2]) %% 1) * 0.998 + 0.001
x <- qnorm(u1); y <- sin(x) + 0.4 * (1 + 0.5 * x^2) * qnorm(u2)
vec("X", x); vec("Y", y)
# the local constant estimate with Gaussian kernels (np's default) at given bandwidths
ex <- c(-1, -0.2, 0.5, 1.3); ey <- c(-0.5, 0.3, 1.0, 0.1)
for (bw in list(c(0.3, 0.5), c(0.6, 0.25))) {
  r <- npcdens(txdat = x, tydat = y, exdat = ex, eydat = ey, bws = bw)
  vec(paste0("NPCDENS_", gsub("\\.", "", paste(bw, collapse = "_"))), fitted(r))
}
vec("EX", ex); vec("EY", ey)
# cross-validated bandwidths, as (bws[1], bws[2]) in np's order
b <- npcdensbw(xdat = x, ydat = y, bwmethod = "cv.ml", nmulti = 10)
vec("CVML", c(b$xbw, b$ybw)); vec("CVML_FVAL", b$fval)
b <- npcdensbw(xdat = x, ydat = y, bwmethod = "cv.ls", nmulti = 10)
vec("CVLS", c(b$xbw, b$ybw)); vec("CVLS_FVAL", b$fval)
# local linear quantile regression
for (tau in c(0.25, 0.5, 0.9)) {
  r <- lprq(x, y, h = 0.4, tau = tau, m = 20)
  t100 <- round(100 * tau)
  vec(paste0("LPRQ_FV_", t100), r$fv); vec(paste0("LPRQ_DV_", t100), r$dv)
}
vec("LPRQ_XX", lprq(x, y, h = 0.4, tau = 0.5, m = 20)$xx)
# weighted linear quantile regression
w <- 1 + (i %% 4)
for (tau in c(0.1, 0.5, 0.75)) vec(paste0("RQ_", round(100 * tau)), coef(rq(y ~ x + I(x^2), tau = tau, weights = w)))
