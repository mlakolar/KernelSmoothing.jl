# Reference values from the R package coneproj (and stats::isoreg) for the shape
# projections of KernelSmoothing.jl. The library with coneproj is the first argument,
# or on the library path.
RLIB <- commandArgs(trailingOnly = TRUE)[1]
if (!is.na(RLIB)) .libPaths(c(RLIB, .libPaths()))
suppressPackageStartupMessages(library(coneproj))
f <- function(v) paste(sprintf("%.17g", v), collapse = ", ")
vec <- function(name, v) cat("const ", name, " = [", f(v), "]\n", sep = "")
cat("# generated by shape_golden.R with coneproj", as.character(packageVersion("coneproj")), "and", R.version.string, "\n")
m <- 25
i <- 1:m
phi <- round(0.6180339887498949 * 2^30) / 2^30
t <- cumsum(0.5 + ((i * phi) %% 1))           # unequally spaced points
y <- sin(t / 3) + 0.3 * cos(3.7 * i)           # a wiggly, partly monotone sequence
w <- 1 + (i %% 3)
vec("T", t); vec("Y", y); vec("W", w)
# constraint matrices: first differences and second divided differences
D1 <- t(sapply(1:(m - 1), function(k) { r <- numeric(m); r[k] <- -1; r[k + 1] <- 1; r }))
D2 <- t(sapply(2:(m - 1), function(k) {
  r <- numeric(m)
  r[k - 1] <- 1 / (t[k] - t[k - 1]); r[k] <- -1 / (t[k] - t[k - 1]) - 1 / (t[k + 1] - t[k]); r[k + 1] <- 1 / (t[k + 1] - t[k])
  r }))
cons <- list(increasing = D1, decreasing = -D1, convex = D2, concave = -D2,
             increasing_convex = rbind(D1[1, ], D2), increasing_concave = rbind(D1[m - 1, ], -D2),
             decreasing_convex = rbind(-D1[m - 1, ], D2), decreasing_concave = rbind(-D1[1, ], -D2))
for (s in names(cons)) {
  vec(paste0("PROJ_", toupper(s)), coneA(y, cons[[s]], w = w, msg = FALSE)$thetahat)
  vec(paste0("PROJU_", toupper(s)), coneA(y, cons[[s]], msg = FALSE)$thetahat)
}
vec("ISOREG", isoreg(t, y)$yf)
# constrained regression fits of cgam and scam (regression splines, so the
# comparison with the projected kernel fits is approximate)
suppressPackageStartupMessages({ library(cgam); library(scam) })
n <- 400
psi <- round(0.7548776662466927 * 2^30) / 2^30
x <- ((1:n) * psi) %% 1
y <- x^2 + 0.2 * sin(31.7 * (1:n))
pts <- seq(0.05, 0.95, length.out = 31)
vec("SX", x); vec("SY", y); vec("SPTS", pts)
nd <- data.frame(x = pts)
vec("CGAM_INCR", predict(cgam(y ~ incr(x)), newdata = nd)$fit)
vec("SCAM_MPI", predict(scam(y ~ s(x, k = 15, bs = "mpi")), newdata = nd))
